  std::optional<UnixSeconds> FileTimeToUnixSeconds(uint64_t file_time) {
    // A zero FILETIME means "not set", it is not the timestamp of a real file
    if (file_time == 0)
      return std::nullopt;

    const auto seconds = static_cast<UnixSeconds>(file_time / static_cast<uint64_t>(k_filetime_ticks_per_second));
    return seconds - k_filetime_unix_epoch_delta;
  }

  UnixSeconds Now() {
    return static_cast<UnixSeconds>(std::time(nullptr));
  }

  bool ToUtcTm(UnixSeconds time, std::tm& out) {
    return ConvertTime(time, out, true);
  }

  bool ToLocalTm(UnixSeconds time, std::tm& out) {
    return ConvertTime(time, out, false);
  }

  std::string FormatISO8601(const std::tm& utc_time) {
    char buf[32];
    std::snprintf(
      buf,
      sizeof buf,
      "%04d-%02d-%02dT%02d:%02d:%02dZ",
      utc_time.tm_year + 1900,
      utc_time.tm_mon + 1,
      utc_time.tm_mday,
      utc_time.tm_hour,
      utc_time.tm_min,
      utc_time.tm_sec
    );
    return buf;
  }

  std::string FormatDotHashTime(const std::tm& local_time) {
    char buf[32];
    std::snprintf(
      buf,
      sizeof buf,
      "%04d.%02d.%02d@%02d.%02d:%02d",
      local_time.tm_year + 1900,
      local_time.tm_mon + 1,
      local_time.tm_mday,
      local_time.tm_hour,
      local_time.tm_min,
      local_time.tm_sec
    );
    return buf;
  }

  std::string FormatBannerTimestamp(UnixSeconds operation_time) {
    std::tm utc{};
    if (!ToUtcTm(operation_time, utc))
      return {};
    return FormatISO8601(utc);
  }

  std::string FormatDotHashTimestamp(
    const std::optional<UnixSeconds>& source_time,
    UnixSeconds operation_time
  ) {
    std::tm local{};
    if (source_time && ToLocalTm(*source_time, local))
      return FormatDotHashTime(local);
    // No usable source time: the export happened now, so that is what we record
    if (ToLocalTm(operation_time, local))
      return FormatDotHashTime(local);
    return {};
  }

  std::string BuildSumfileText(
    const std::vector<SumfileEntry>& files,
    const SumfileOptions& options,
    std::string_view version,
    UnixSeconds operation_time
  ) {
    std::stringstream ss;
    const auto line_end = options.for_clipboard || options.dot_hash || !options.unix_endings ? "\r\n" : "\n";
    const auto separator = (!options.dot_hash && options.double_space) ? "  " : " *";
    const auto forward_slashes = !options.dot_hash && options.forward_slashes;
    const auto dot_hash_compatible = options.dot_hash || options.dot_hash_compatible;

    if (!options.for_clipboard && options.banner)
      AppendBanner(ss, options, version, operation_time, '#', line_end);

    std::vector<std::string> hash_names_dothash;
    hash_names_dothash.reserve(options.hash_names.size());
    for (const auto& name : options.hash_names)
      hash_names_dothash.push_back(LowercaseNoDash(name));

    for (const auto& file : files) {
      if (file.error)
        continue;

      const auto& filename_original = file.filename;
      auto filename = filename_original;
      if (forward_slashes)
        std::replace(begin(filename), end(filename), '\\', '/');

      const auto write_hash = [&](size_t idx) {
        const auto hash = HashHexAt(file, idx, options.uppercase);
        if (dot_hash_compatible && idx < hash_names_dothash.size())
          ss << "#" << hash_names_dothash[idx] << "#" << filename_original << "#"
             << FormatDotHashTimestamp(file.source_time, operation_time) << line_end;
        ss << hash << separator << filename << line_end;
      };

      if (!options.dot_hash) {
        write_hash(options.algorithm);
      } else {
        for (auto i = 0u; i < options.enabled_algorithms.size(); ++i)
          if (options.enabled_algorithms[i])
            write_hash(i);
      }
    }

    return ss.str();
  }

  std::string BuildSfvText(
    const std::vector<SumfileEntry>& files,
    const SumfileOptions& options,
    std::string_view version,
    UnixSeconds operation_time
  ) {
    std::stringstream ss;
    const auto line_end = options.for_clipboard || !options.unix_endings ? "\r\n" : "\n";

    if (!options.for_clipboard && options.banner)
      AppendBanner(ss, options, version, operation_time, ';', line_end);

    for (const auto& file : files) {
      if (file.error)
        continue;

      auto filename = file.filename;
      if (options.forward_slashes)
        std::replace(begin(filename), end(filename), '\\', '/');

      ss << filename << " " << HashHexAt(file, options.algorithm, options.uppercase) << line_end;
    }

    return ss.str();
  }

