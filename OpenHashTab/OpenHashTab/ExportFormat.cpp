    char HexDigit(uint8_t nibble, bool upper) {
      if (nibble < 0xA)
        return static_cast<char>('0' + nibble);
      return static_cast<char>((upper ? 'A' : 'a') + (nibble - 0xA));
    }

    std::string HexEncode(const std::vector<uint8_t>& hash, bool upper) {
      std::string out(hash.size() * 2, '\0');
      for (size_t i = 0; i < hash.size(); ++i) {
        out[i * 2] = HexDigit(static_cast<uint8_t>(hash[i] >> 4), upper);
        out[i * 2 + 1] = HexDigit(static_cast<uint8_t>(hash[i] & 0xF), upper);
      }
      return out;
    }

    // .hash metadata lines use the algorithm name lowercased and without dashes, e.g. "SHA-256" becomes "sha256"
    std::string LowercaseNoDash(std::string_view name) {
      std::string out;
      out.reserve(name.size());
      for (const auto c : name) {
        if (c == '-')
          continue;
        const auto uc = static_cast<unsigned char>(c);
        out.push_back(static_cast<char>(uc >= 'A' && uc <= 'Z' ? uc - 'A' + 'a' : uc));
      }
      return out;
    }

    bool ConvertTime(UnixSeconds time, std::tm& out, bool utc) {
      if (time < 0)
        return false;

      const auto tt = static_cast<std::time_t>(time);
      // time_t might be narrower than our input on some platforms
      if (static_cast<UnixSeconds>(tt) != time)
        return false;

      std::tm result{};
#if defined(_MSC_VER) || defined(__MINGW32__)
      // Both use the MSVC argument order: (result, time)
      const auto error = utc ? gmtime_s(&result, &tt) : localtime_s(&result, &tt);
      if (error != 0)
        return false;
#elif defined(__unix__) || defined(__APPLE__)
      const auto converted = utc ? gmtime_r(&tt, &result) : localtime_r(&tt, &result);
      if (!converted)
        return false;
#else
      const std::lock_guard<std::mutex> lock{s_tm_mutex};
      const auto* converted = utc ? gmtime(&tt) : localtime(&tt);
      if (!converted)
        return false;
      result = *converted;
#endif

      out = result;
      return true;
    }

    void AppendBanner(
      std::stringstream& ss,
      const SumfileOptions& options,
      std::string_view version,
      UnixSeconds operation_time,
      char comment,
      const char* line_end
    ) {
      ss << comment << " Generated by OpenHashTab " << version;
      if (options.banner_date)
        ss << " at " << FormatBannerTimestamp(operation_time);
      ss << line_end;
      ss << comment << " https://github.com/namazso/OpenHashTab/" << line_end;
      ss << comment << line_end;
    }

    std::string HashHexAt(const SumfileEntry& file, size_t idx, bool upper) {
      if (idx >= file.hashes.size())
        return {};
      return HexEncode(file.hashes[idx], upper);
    }

